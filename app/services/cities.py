# 按地区分组，供下拉框使用（保持插入顺序）
CITY_GROUPS: dict[str, list[str]] = {}
for _name, (_, _, _group) in _CITY_DATA.items():
    CITY_GROUPS.setdefault(_group, []).append(_name)


def lookup_city(name: str) -> dict | None:
    """本地查表。命中返回与 Geocoding 相同结构的字典。"""
    entry = _CITY_DATA.get(name)
    if not entry:
        return None
    lat, lon, region = entry
    return {
        "name": name,
        "latitude": lat,
        "longitude": lon,
        "country": "中国" if region not in ("国际", "港澳台") else "",
        "admin1": region,
    }


def all_city_names() -> list[str]:
    return list(_CITY_DATA.keys())